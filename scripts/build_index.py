def one_liner(d):
    p = f"{ROOT}/papers/{d}/解读.md"
    if not os.path.exists(p):
        return "（解读待生成）"
    body = open(p, encoding="utf-8").read()
    m = re.search(r"^## 1\.[^\n]*\n+(.+?)(?=\n\n|\n## )", body, re.S | re.M)
    if not m:
        return "—"
    s = " ".join(m.group(1).split())
    out = (re.split(r"(?<=。)", s) or [s])[0]
    if len(out) > 190:
        out = out[:188] + "……"
    return out.replace("|", "／")


