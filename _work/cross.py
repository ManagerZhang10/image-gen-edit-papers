import json,os,sys,glob,re
sys.path.insert(0,"_work")
from synth import deepseek
ts=json.load(open("_work/threads.json",encoding="utf-8"))
parts=[]
for i,t in enumerate(ts):
    s=open(f"_work/syn_{i}.md",encoding="utf-8").read()
    names="、".join(p["short"] for p in t["papers"])
    parts.append(f"## 脉络 {i+1}：{t['name']}（{len(t['papers'])} 篇：{names}）\n\n{s}")
mat="\n\n".join(parts)

SYS="""你在给一个 160 篇的图像编辑论文库写「横向总结」。素材是 15 条脉络各自的综述。

硬规则：
- 事实只能来自素材。素材没写的不要补。不写引用量、社区评价、后续产品。
- 禁止营销词：碾压、吊打、开山之作、革命性、里程碑、颠覆、赋能。
- 禁止凑数章节和元话语。不要写「总结」「展望」「综上所述」「本节将」。
- 中文，术语保留英文原词。对照关系一律用表格。
- 每个判断都要能指回具体论文名，不要写「许多工作表明」这种没有落点的话。

严格输出下面四个部分，用我给的小标题，不要加别的：

### A. 先破一个误解
读者最容易想当然的一个认知错误，用素材证明它错在哪。一个「你以为 / 实际」表格（3~5 行）+ 三四句话解释。
选那个真正会影响技术判断的误解，不要选无关痛痒的。

### B. 五年里真正的转折点
一个表格，4~6 行。列：`时间 | 转折 | 触发它的工作 | 之前怎么做 → 之后怎么做`。
只选那些「之后大部分工作都改了做法」的转折，不要把每个热点都算转折。
表格下接一段话，说清这些转折之间是不是有因果关系。

### C. 横向反复出现的模式
5~7 条，跨脉络出现过两次以上的共性模式。每条格式：
`- **模式名** —— 在哪几条线上出现（点名论文），它为什么反复有效`

### D. 全领域还没解决的
一个表格，5~7 行。列：`问题 | 具体表现（点名论文和现象） | 为什么难`。
把 15 条脉络各自的「还没解决的」去重合并，只留真正跨脉络反复出现的。"""

r=deepseek(SYS,mat[:400000],max_tokens=16000,temp=0.3)
open("_work/cross.md","w",encoding="utf-8").write(r.strip())
print("OK",len(r))
